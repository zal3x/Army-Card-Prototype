#!/usr/bin/env python3
"""Render the Cascaders sound pack.

Usage:
    python3 build.py                       # render everything into the Unity project
    python3 build.py --only Soul_Taken     # render names containing a substring
    python3 build.py --preview DIR         # also write MP3 previews + manifest.json to DIR

Requires: numpy, scipy, ffmpeg (for the .ogg music files and MP3 previews).
Every sound is seeded from its name, so re-running produces identical files.
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile
import time
import zlib
from concurrent.futures import ProcessPoolExecutor

import numpy as np
from scipy.io import wavfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from dsp import SR, master_sfx, master_music  # noqa: E402
import sfx  # noqa: E402
import music  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "Assets", "Audio", "Cascaders Sound Pack")


def to_int16(x):
    return (np.clip(x, -1, 1).T * 32767).astype(np.int16)


def ffmpeg(src, dst, *args):
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, *args, dst], check=True)


def render(job):
    kind, folder, name, loop = job
    rng = np.random.default_rng(zlib.crc32(name.encode()))
    t0 = time.time()
    if kind == "sfx":
        fn = dict((n, f) for _, n, f in sfx.SFX)[name]
        audio = master_sfx(fn(rng))
    else:
        fn = dict((n, f) for _, n, f, _ in music.MUSIC)[name]
        audio = master_music(fn(rng), loop=loop)
    if not np.all(np.isfinite(audio)):
        raise RuntimeError(f"{name}: non-finite samples")
    return dict(kind=kind, folder=folder, name=name, loop=loop, audio=to_int16(audio),
                description=" ".join((fn.__doc__ or "").split()),
                seconds=round(audio.shape[1] / SR, 2), render_time=round(time.time() - t0, 1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--preview", default="")
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 2)
    args = ap.parse_args()

    jobs = [("sfx", f, n, False) for f, n, _ in sfx.SFX]
    jobs += [("music", "Music/" + f, n, loop) for f, n, _, loop in music.MUSIC]
    jobs = [j for j in jobs if args.only.lower() in j[2].lower()]
    # Longest jobs first so the pool stays busy
    jobs.sort(key=lambda j: j[0] != "music")

    manifest = []
    with ProcessPoolExecutor(args.jobs) as pool, tempfile.TemporaryDirectory() as tmp:
        for res in pool.map(render, jobs):
            folder = os.path.join(OUT, res["folder"])
            os.makedirs(folder, exist_ok=True)
            if res["kind"] == "sfx":
                path = os.path.join(folder, res["name"] + ".wav")
                wavfile.write(path, SR, res["audio"])
            else:
                wav = os.path.join(tmp, res["name"] + ".wav")
                wavfile.write(wav, SR, res["audio"])
                path = os.path.join(folder, res["name"] + ".ogg")
                ffmpeg(wav, path, "-c:a", "libvorbis", "-q:a", "7")
            if args.preview:
                os.makedirs(args.preview, exist_ok=True)
                prev = os.path.join(args.preview, res["name"] + ".mp3")
                ffmpeg(path, prev, "-c:a", "libmp3lame", "-b:a", "160k")
            rel = os.path.relpath(path, ROOT)
            peak = np.max(np.abs(res["audio"])) / 32767
            print(f"{res['render_time']:>5}s  {res['seconds']:>6}s  peak {20*np.log10(peak+1e-9):6.1f} dB  {rel}")
            manifest.append(dict(name=res["name"], folder=res["folder"], kind=res["kind"],
                                 loop=res["loop"], seconds=res["seconds"], path=rel,
                                 description=res["description"]))
    if args.preview:
        with open(os.path.join(args.preview, "manifest.json"), "w") as f:
            json.dump(manifest, f, indent=1)
    if not args.only:
        write_readme(manifest)


def write_readme(manifest):
    lines = [
        "# Cascaders Sound Pack",
        "",
        "Dark metal / grunge / synth sound effects and music cues, generated by",
        "`Tools/CascadersSoundPack/build.py` (re-run it to regenerate; output is deterministic).",
        "",
        "* SFX: 44.1 kHz 16-bit stereo WAV, peaks at -1 dBFS, levelled to a common",
        "  loudness (about -16 dB active RMS) so variants can be swapped without volume jumps.",
        "* Music: Ogg Vorbis. Files marked **loop** are sample-accurate loops: the reverb",
        "  and ringing chords at the end are folded onto the start, so tick *Loop* on the",
        "  AudioSource and they repeat seamlessly.",
        "* Import tip: set short SFX to *Decompress On Load*, music to *Streaming*.",
        "",
    ]
    section = None
    for e in sorted(manifest, key=lambda e: (e["kind"] != "music", e["folder"], e["name"])):
        top = e["folder"].split("/")[0] if e["kind"] == "sfx" else "Music"
        if top != section:
            section = top
            lines += ["", f"## {section}", "", "| File | Length | Description |", "|---|---|---|"]
        name = os.path.basename(e["path"])
        loop = " **loop**" if e["loop"] else ""
        lines.append(f"| `{e['folder']}/{name}` | {e['seconds']:.1f}s{loop} | {e['description']} |")
    with open(os.path.join(OUT, "README.md"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
